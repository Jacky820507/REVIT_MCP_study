<#
.SYNOPSIS
    Verify a generated RevitMCP .xlsx workbook with OfficeCLI.

.DESCRIPTION
    This is an offline QA gate for OpenXML workbooks generated by pyRevit.
    It validates the package, reads the workbook outline, and inspects
    OfficeCLI's formula/layout issue report. It is intentionally separate
    from the IronPython button runtime: legacy .xls files and in-place
    formatting preservation remain the responsibility of Excel COM.

.PARAMETER WorkbookPath
    The .xlsx file to inspect. .xls is rejected because OfficeCLI's xlsx
    handler does not support the legacy BIFF format.

.PARAMETER OfficeCliPath
    Optional full path to officecli.ps1/cmd. If omitted, officecli is looked
    up through PATH.

.PARAMETER ReportPath
    Optional path for a JSON report.

.PARAMETER RenderHtml
    Also render the workbook to HTML for visual inspection.

.PARAMETER RenderPath
    Optional output path for the HTML render. Defaults to
    <WorkbookPath>.officecli.html when -RenderHtml is used.

.PARAMETER FailOnLayoutWarnings
    Treat OfficeCLI layout warnings such as merged-cell text overflow as
    failures. The default is to report them as warnings only because a
    user's existing row heights may be intentional.

.EXAMPLE
    .\verify-officecli-xlsx.ps1 .\tmp\InteriorWallPaint_bottom_ray_test.xlsx

.EXAMPLE
    .\verify-officecli-xlsx.ps1 .\out.xlsx -RenderHtml -ReportPath .\out.qa.json
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true, Position = 0)]
    [string] $WorkbookPath,

    [string] $OfficeCliPath,

    [string] $ReportPath,

    [switch] $RenderHtml,

    [string] $RenderPath,

    [switch] $FailOnLayoutWarnings
)

$ErrorActionPreference = 'Stop'

function Resolve-OfficeCli {
    param([string] $RequestedPath)

    if ($RequestedPath) {
        if (-not (Test-Path -LiteralPath $RequestedPath -PathType Leaf)) {
            throw "OfficeCLI executable not found: $RequestedPath"
        }
        return (Resolve-Path -LiteralPath $RequestedPath).Path
    }

    $command = Get-Command officecli -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if (-not $command) {
        throw "officecli was not found on PATH. Install OfficeCLI or pass -OfficeCliPath."
    }
    return $command.Source
}

function Invoke-OfficeCliJson {
    param(
        [string] $Cli,
        [string[]] $Arguments
    )

    $raw = & $Cli @Arguments 2>&1
    $exitCode = $LASTEXITCODE
    $text = ($raw | Out-String).Trim()

    if ($exitCode -ne 0) {
        throw "OfficeCLI failed (exit $exitCode): $text"
    }
    if (-not $text) {
        throw "OfficeCLI returned no JSON for: officecli $($Arguments -join ' ')"
    }

    try {
        return ($text | ConvertFrom-Json)
    }
    catch {
        throw "OfficeCLI returned invalid JSON for: officecli $($Arguments -join ' ')`n$text"
    }
}

function Invoke-OfficeCliCommand {
    param(
        [string] $Cli,
        [string[]] $Arguments
    )

    & $Cli @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "OfficeCLI failed (exit $LASTEXITCODE): officecli $($Arguments -join ' ')"
    }
}

try {
    $resolvedWorkbook = (Resolve-Path -LiteralPath $WorkbookPath -ErrorAction Stop).Path
    $extension = [IO.Path]::GetExtension($resolvedWorkbook).ToLowerInvariant()
    if ($extension -ne '.xlsx') {
        throw "OfficeCLI QA requires .xlsx; received '$extension'. Keep .xls publication on the Excel COM path."
    }

    $cli = Resolve-OfficeCli $OfficeCliPath
    $version = (& $cli --version 2>&1 | Out-String).Trim()
    if ($LASTEXITCODE -ne 0) {
        throw "Unable to read OfficeCLI version from $cli"
    }

    $validate = Invoke-OfficeCliJson $cli @('validate', $resolvedWorkbook, '--json')
    $outline = Invoke-OfficeCliJson $cli @('view', $resolvedWorkbook, 'outline', '--json')
    $issues = Invoke-OfficeCliJson $cli @('view', $resolvedWorkbook, 'issues', '--json')

    $schemaErrors = @()
    if ($validate.data -and $validate.data.errors) {
        $schemaErrors = @($validate.data.errors)
    }

    $sheets = @()
    if ($outline.data -and $outline.data.sheets) {
        $sheets = @($outline.data.sheets)
    }

    $issueList = @()
    if ($issues.data -and $issues.data.issues) {
        $issueList = @($issues.data.issues)
    }

    $formulaIssues = @($issueList | Where-Object {
        $_.subtype -in @(
            'formula_eval_error',
            'formula_ref_missing_sheet',
            'formula_not_evaluated',
            'definedname_broken',
            'definedname_target_missing'
        )
    })
    $staleCacheWarnings = @($issueList | Where-Object {
        $_.subtype -eq 'formula_cache_stale'
    })
    $layoutWarnings = @($issueList | Where-Object {
        $_.type -eq 0 -and $_.subtype -notin @('formula_cache_stale')
    })

    $errorCellCount = 0
    $formulaCount = 0
    foreach ($sheet in $sheets) {
        $errorCellCount += [int]$sheet.errorCells
        $formulaCount += [int]$sheet.formulas
    }

    if ($RenderHtml) {
        if (-not $RenderPath) {
            $RenderPath = "$resolvedWorkbook.officecli.html"
        }
        $renderParent = Split-Path -Parent $RenderPath
        if ($renderParent -and -not (Test-Path -LiteralPath $renderParent)) {
            New-Item -ItemType Directory -Path $renderParent -Force | Out-Null
        }
        Invoke-OfficeCliCommand $cli @('view', $resolvedWorkbook, 'html', '--out', $RenderPath)
    }

    $report = [ordered]@{
        success = $true
        workbook = $resolvedWorkbook
        officecli = $version
        schemaErrors = $schemaErrors
        sheetCount = $sheets.Count
        formulaCount = $formulaCount
        errorCellCount = $errorCellCount
        formulaIssues = $formulaIssues
        staleCacheWarnings = $staleCacheWarnings
        layoutWarnings = $layoutWarnings
        renderedHtml = if ($RenderHtml) { $RenderPath } else { $null }
        passed = ($schemaErrors.Count -eq 0 -and
            $formulaIssues.Count -eq 0 -and
            $errorCellCount -eq 0 -and
            (-not $FailOnLayoutWarnings -or $layoutWarnings.Count -eq 0))
    }

    if ($ReportPath) {
        $reportParent = Split-Path -Parent $ReportPath
        if ($reportParent -and -not (Test-Path -LiteralPath $reportParent)) {
            New-Item -ItemType Directory -Path $reportParent -Force | Out-Null
        }
        $report | ConvertTo-Json -Depth 20 | Set-Content -LiteralPath $ReportPath -Encoding UTF8
    }

    Write-Output 'OfficeCLI xlsx QA'
    Write-Output "  workbook       : $resolvedWorkbook"
    Write-Output "  officecli      : $version"
    Write-Output "  sheets         : $($sheets.Count)"
    Write-Output "  formulas       : $formulaCount"
    Write-Output "  error cells    : $errorCellCount"
    Write-Output "  formula issues : $($formulaIssues.Count)"
    Write-Output "  stale caches   : $($staleCacheWarnings.Count)"
    Write-Output "  layout warning : $($layoutWarnings.Count)"
    if ($RenderHtml) { Write-Output "  html           : $RenderPath" }
    if ($ReportPath) { Write-Output "  report         : $ReportPath" }

    if ($formulaIssues.Count -gt 0) {
        Write-Output ''
        Write-Output 'Formula issue locations:'
        $formulaIssues | Select-Object -First 20 | ForEach-Object {
            Write-Output "  $($_.path) - $($_.subtype): $($_.message)"
        }
        if ($formulaIssues.Count -gt 20) {
            Write-Output "  ... $($formulaIssues.Count - 20) more"
        }
    }

    if ($layoutWarnings.Count -gt 0) {
        Write-Output ''
        Write-Output 'Layout warnings (first 10):'
        $layoutWarnings | Select-Object -First 10 | ForEach-Object {
            Write-Output "  $($_.path) - $($_.message)"
        }
    }

    if (-not $report.passed) {
        Write-Output ''
        Write-Output 'RESULT: FAILED'
        exit 1
    }

    Write-Output 'RESULT: PASSED'
    exit 0
}
catch {
    Write-Error $_.Exception.Message
    exit 2
}
